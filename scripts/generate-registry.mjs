#!/usr/bin/env node
// Scans src/crafts/*/ (meta.ts + craft.tsx) and src/designs/*/ (meta.ts) and
// writes the generated registries. Runs before `dev` and `build`.

import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CRAFTS_DIR = join(ROOT, "src", "crafts");
export const DESIGNS_DIR = join(ROOT, "src", "designs");
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const HEADER = [
  "// Generated by scripts/generate-registry.mjs — do not edit by hand.",
];

function scan(dir, required, label, log) {
  const slugs = [];
  if (!existsSync(dir)) return slugs;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith("_")) continue;
    const slug = entry.name;
    const missing = required.filter((file) => !existsSync(join(dir, slug, file)));
    if (missing.length) {
      if (log) console.warn(`${label}: skipping "${slug}" — missing ${missing.join(", ")}`);
      continue;
    }
    if (!SLUG.test(slug)) throw new Error(`${label}: "${slug}" is not a valid slug (lowercase letters, digits and dashes only)`);
    slugs.push(slug);
  }
  return slugs.sort();
}

function write(file, next, log, what) {
  const prev = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (prev === next) return false;
  writeFileSync(file, next);
  if (log) console.log(what);
  return true;
}

export function generateRegistry({ log = true } = {}) {
  const crafts = scan(CRAFTS_DIR, ["meta.ts", "craft.tsx"], "crafts", log);
  const designs = scan(DESIGNS_DIR, ["meta.ts"], "designs", log);

  write(
    join(CRAFTS_DIR, "_metas.ts"),
    [
      ...HEADER,
      "// Add a craft with `npm run new <slug>` or by creating src/crafts/<slug>/{meta.ts,craft.tsx}.",
      'import type { CraftMeta } from "./types";',
      "",
      ...crafts.map((slug, i) => `import meta${i} from "./${slug}/meta";`),
      "",
      "export const metas: { slug: string; meta: CraftMeta }[] = [",
      ...crafts.map((slug, i) => `  { slug: "${slug}", meta: meta${i} },`),
      "];",
      "",
    ].join("\n"),
    log,
    `crafts: registry updated (${crafts.length})`,
  );
  write(
    join(CRAFTS_DIR, "_registry.ts"),
    [
      ...HEADER,
      "// Add a craft with `npm run new <slug>` or by creating src/crafts/<slug>/{meta.ts,craft.tsx}.",
      'import type { CraftComponent } from "./types";',
      "",
      ...crafts.map((slug, i) => `import Craft${i} from "./${slug}/craft";`),
      "",
      "export const components: Record<string, CraftComponent> = {",
      ...crafts.map((slug, i) => `  "${slug}": Craft${i},`),
      "};",
      "",
    ].join("\n"),
    log,
    `crafts: components updated (${crafts.length})`,
  );
  write(
    join(DESIGNS_DIR, "_metas.ts"),
    [
      ...HEADER,
      "// Add a design with `npm run new:design <slug>` or by creating src/designs/<slug>/meta.ts next to its image.",
      'import type { DesignMeta } from "./types";',
      "",
      ...designs.map((slug, i) => `import meta${i} from "./${slug}/meta";`),
      "",
      "export const metas: { slug: string; meta: DesignMeta }[] = [",
      ...designs.map((slug, i) => `  { slug: "${slug}", meta: meta${i} },`),
      "];",
      "",
    ].join("\n"),
    log,
    `designs: registry updated (${designs.length})`,
  );
  if (log) console.log(`registry: ${crafts.length} craft${crafts.length === 1 ? "" : "s"}, ${designs.length} design${designs.length === 1 ? "" : "s"}`);
  return { crafts, designs };
}

const invokedDirectly =
  process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
if (invokedDirectly) generateRegistry();
