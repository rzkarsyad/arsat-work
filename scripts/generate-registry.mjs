#!/usr/bin/env node
// Scans src/crafts/*/ for folders that contain meta.ts and craft.tsx and
// writes src/crafts/_registry.ts. Runs before `dev` and `build`.

import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CRAFTS_DIR = join(ROOT, "src", "crafts");
const METAS_OUT = join(CRAFTS_DIR, "_metas.ts");
const REGISTRY_OUT = join(CRAFTS_DIR, "_registry.ts");
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function generateRegistry({ log = true } = {}) {
  const slugs = [];
  for (const entry of readdirSync(CRAFTS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith("_")) continue;
    const slug = entry.name;
    const dir = join(CRAFTS_DIR, slug);
    if (!existsSync(join(dir, "meta.ts")) || !existsSync(join(dir, "craft.tsx"))) {
      if (log) console.warn(`crafts: skipping "${slug}" — needs both meta.ts and craft.tsx`);
      continue;
    }
    if (!SLUG.test(slug)) {
      throw new Error(`crafts: "${slug}" is not a valid slug (lowercase letters, digits and dashes only)`);
    }
    slugs.push(slug);
  }
  slugs.sort();

  const header = [
    "// Generated by scripts/generate-registry.mjs — do not edit by hand.",
    "// Add a craft with `npm run new <slug>` or by creating src/crafts/<slug>/{meta.ts,craft.tsx}.",
  ];

  // _metas.ts: data only, safe to import from server code (pages, feed, sitemap, OG images).
  const metas = [
    ...header,
    'import type { CraftMeta } from "./types";',
    "",
    ...slugs.map((slug, i) => `import meta${i} from "./${slug}/meta";`),
    "",
    "export const metas: { slug: string; meta: CraftMeta }[] = [",
    ...slugs.map((slug, i) => `  { slug: "${slug}", meta: meta${i} },`),
    "];",
    "",
  ].join("\n");

  // _registry.ts: the client components, keyed by slug.
  const registry = [
    ...header,
    'import type { CraftComponent } from "./types";',
    "",
    ...slugs.map((slug, i) => `import Craft${i} from "./${slug}/craft";`),
    "",
    "export const components: Record<string, CraftComponent> = {",
    ...slugs.map((slug, i) => `  "${slug}": Craft${i},`),
    "};",
    "",
  ].join("\n");

  let changed = false;
  for (const [file, next] of [[METAS_OUT, metas], [REGISTRY_OUT, registry]]) {
    const prev = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (prev !== next) {
      writeFileSync(file, next);
      changed = true;
    }
  }
  if (log) {
    console.log(
      changed
        ? `crafts: registry updated (${slugs.length} craft${slugs.length === 1 ? "" : "s"})`
        : `crafts: registry up to date (${slugs.length})`,
    );
  }
  return slugs;
}

const invokedDirectly =
  process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
if (invokedDirectly) generateRegistry();
